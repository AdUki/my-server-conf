#!/bin/bash
# Restore the Immich database into an empty DB_DATA_LOCATION.
#
# Usage: restore-db.sh [dump]
#   dump defaults to the newest of Immich's own nightly backups in
#   UPLOAD_LOCATION/backups/immich-db-backup-*.sql.gz. A pg_dumpall file
#   (do-backup.sh writes one to UPLOAD_LOCATION/database-backup/) also works.
#
# Follows https://docs.immich.app/administration/backup-and-restore: only the
# postgres container runs while the dump loads, so the server never gets to
# initialise or migrate an empty database first. An existing data dir is moved
# aside, never deleted. setup.sh calls this itself when it finds an empty
# database next to a library that has backups (the "NVMe died" case).
set -e
SCRIPT_DIR="$(realpath "$(dirname "$0")")"
cd "$SCRIPT_DIR"
source "$SCRIPT_DIR/.env"

DUMP="${1:-$(ls -1 "$UPLOAD_LOCATION"/backups/immich-db-backup-*.sql.gz 2>/dev/null | sort | tail -1)}"
[ -f "$DUMP" ] || { echo "No database dump found (looked in $UPLOAD_LOCATION/backups/)" >&2; exit 1; }

DOCKER=docker
docker info >/dev/null 2>&1 || DOCKER="sudo docker"

case "$DUMP" in
	*.gz) CAT="gunzip --stdout" ;;
	*)    CAT=cat ;;
esac

# pg_dumpall output drops/creates the immich database itself, so it has to be
# loaded through the maintenance database and cannot run in one transaction.
if $CAT "$DUMP" | head -3 | grep -q 'database cluster dump'; then
	PSQL_ARGS=(--dbname=postgres)
else
	PSQL_ARGS=(--dbname="$DB_DATABASE_NAME" --single-transaction)
fi

echo "Restoring $DUMP into $DB_DATA_LOCATION"
$DOCKER compose down 2>/dev/null || true

if [ -n "$(sudo ls -A "$DB_DATA_LOCATION" 2>/dev/null)" ]; then
	ASIDE="$DB_DATA_LOCATION.replaced-$(date +%Y%m%d-%H%M%S)"
	echo "Moving the existing database dir aside to $ASIDE"
	sudo mv "$DB_DATA_LOCATION" "$ASIDE"
fi
sudo mkdir -p "$DB_DATA_LOCATION"

$DOCKER compose create
$DOCKER start immich_postgres
# The image's entrypoint runs initdb on a socket-only temporary server first;
# TCP only answers once the real server is up.
until $DOCKER exec immich_postgres pg_isready -h 127.0.0.1 -U "$DB_USERNAME" >/dev/null 2>&1; do sleep 2; done
sleep 3

# The search_path rewrite is from the Immich docs; \restrict markers (pg_dump
# >= 14.19) are dropped so older psql builds do not choke on them.
$CAT "$DUMP" \
	| sed -e "s/SELECT pg_catalog.set_config('search_path', '', false);/SELECT pg_catalog.set_config('search_path', 'public, pg_catalog', true);/g" \
	      -e '/^\\restrict /d' -e '/^\\unrestrict /d' \
	| $DOCKER exec -i immich_postgres psql --username="$DB_USERNAME" "${PSQL_ARGS[@]}" --set ON_ERROR_STOP=on >/dev/null

$DOCKER compose up -d
echo "Database restored from $DUMP."
echo "Missing thumbnails are regenerated by Immich's 'Generate Thumbnails' job (Administration > Jobs > Missing)."
